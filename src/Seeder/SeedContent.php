    /** @return list<array<string, string>> */
    public function categories(SeedOptions $options): array
    {
        $result = [];
        $createdAt = $options->date->format('Y-m-d 00:00:00');
        for ($index = 0; $index < $options->categories - 1; $index++) {
            [$slug, $name, $description] = self::CATEGORIES[$index] ?? [
                'practice-' . ($index + 1),
                'Практика проектирования ' . ($index + 1),
                'Наблюдения, примеры и способы проверить инженерное решение в работе.',
            ];
            $result[] = compact('slug', 'name', 'description') + ['created_at' => $createdAt];
        }
        $result[] = [
            'slug' => 'editorial-notes',
            'name' => 'Заметки редакции',
            'description' => 'Будущие публикации редакции. Раздел пока не содержит статей.',
            'created_at' => $createdAt,
        ];

        return $result;
    }

    /** @return array<string, mixed> */
    public function post(int $number, SeedOptions $options, array $categories): array
    {
        [$slug, $title, $description, $intro, $practice] = self::TOPICS[($number - 1) % count(self::TOPICS)];
        $edition = intdiv($number - 1, count(self::TOPICS)) + 1;
        if ($edition > 1) {
            $slug .= '-' . $edition;
            $title .= ': практический пример ' . $edition;
        }
        $publishedAt = $options->date
            ->modify('-' . (1 + (intdiv($number - 1, 2) * 17) % 360) . ' days')
            ->setTime(12, 0)
            ->format('Y-m-d H:i:s');
        // All prose is escaped; the markup and the only href are controlled literals.
        $escape = static fn (string $text): string => htmlspecialchars($text, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
        $content = '<p>' . $escape($intro) . '</p>'
            . '<h2>С чего начать</h2><p>' . $escape($practice) . '</p>'
            . '<h3>Проверка на практике</h3><ul>'
            . '<li>Опишите ожидаемое поведение до изменения кода.</li>'
            . '<li>Проверьте обычный сценарий и один граничный случай.</li>'
            . '<li>Сохраните результат, чтобы сравнить его после следующего изменения.</li></ul>'
            . '<blockquote>Хорошее решение можно объяснить, проверить и изменить.</blockquote>'
            . '<p>В этом разборе используется пример № ' . $number
            . '. Отделяйте <strong>наблюдаемые факты</strong> от <em>предположений</em>.</p>'
            . '<ol><li>Зафиксируйте исходное состояние.</li><li>Сравните результат с ожиданием.</li></ol>'
            . '<p>Другие подходы собраны в разделе <a href="/category/architecture">«Архитектура»</a>.</p>';

        $assigned = [$categories[0]['slug']];
        $sharedCount = count($categories) - 2;
        if ($number % 2 === 0 && $sharedCount > 1) {
            $assigned[] = $categories[1 + (intdiv($number, 2) % ($sharedCount - 1))]['slug'];
            if ($number % 4 === 0 && $sharedCount > 2) {
                $assigned[] = $categories[1 + ((intdiv($number, 2) + 1) % ($sharedCount - 1))]['slug'];
            }
        }
        if ($number === $options->posts) {
            $assigned = [$categories[count($categories) - 2]['slug']];
        }

        return [
            'slug' => $slug,
            'title' => $title,
            'description' => $description,
            'content' => $content,
            'views' => match ($number) {
                1 => 0,
                2 => 5000,
                default => ($number * 811 + 97) % 5001,
            },
            'published_at' => $publishedAt,
            'created_at' => $publishedAt,
            'categories' => $assigned,
        ];
    }
